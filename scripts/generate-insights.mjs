// Generates (1) lib/insights.generated.ts — fallback posts used when Supabase is unreachable — and
// (2) an idempotent SQL migration that inserts the same posts into Supabase.
// Source of truth: content/insights/index.json + the Markdown files next to it.
// Usage: node scripts/generate-insights.mjs
import { readFileSync, writeFileSync } from "fs"
import { resolve } from "path"

const root = process.cwd()
const dir = resolve(root, "content/insights")
const posts = JSON.parse(readFileSync(resolve(dir, "index.json"), "utf-8")).map((post) => ({
  ...post,
  content: readFileSync(resolve(dir, post.file), "utf-8").replace(/\r\n/g, "\n").trim(),
}))

const ts = `// AUTO-GENERATED by scripts/generate-insights.mjs — edit content/insights/* instead.
import type { Post } from "@/lib/content"

export const fallbackPosts: Post[] = ${JSON.stringify(
  posts.map((post) => ({ id: post.slug, title: post.title, slug: post.slug, excerpt: post.excerpt, content: post.content, coverImage: post.coverImage, publishedAt: post.publishedAt, sortOrder: post.sortOrder, published: true })),
  null,
  2
)}
`
writeFileSync(resolve(root, "lib/insights.generated.ts"), ts)

const q = (value) => `$rgs$${value}$rgs$`
const sql = `-- AUTO-GENERATED by scripts/generate-insights.mjs — insert-if-missing, never overwrites admin edits.
insert into posts (title, slug, excerpt, content, cover_image, published_at, sort_order, published) values
${posts.map((post) => `(${q(post.title)}, ${q(post.slug)}, ${q(post.excerpt)}, ${q(post.content)}, ${q(post.coverImage)}, ${q(post.publishedAt)}::timestamptz, ${post.sortOrder}, true)`).join(",\n")}
on conflict (slug) do nothing;
`
writeFileSync(resolve(root, "supabase/migrations/20261003_03_insights.sql"), sql)
console.log(`Generated ${posts.length} post(s).`)
